func TestParseHexMetadata(t *testing.T) {
	body := `{<<"name">>, <<"gleam_stdlib"/utf8>>}.
{<<"licenses">>, [<<"Apache-2.0"/utf8>>]}.
{<<"files">>, [
  <<"LICENCE"/utf8>>
]}.
`
	got := parseHexMetadata(body)
	if want := []string{"Apache-2.0"}; !reflect.DeepEqual(got, want) {
		t.Errorf("parseHexMetadata = %v, want %v", got, want)
	}

	dual := `{<<"licenses">>, [<<"MIT">>, <<"Apache-2.0"/utf8>>]}.`
	if got, want := parseHexMetadata(dual), []string{"MIT", "Apache-2.0"}; !reflect.DeepEqual(got, want) {
		t.Errorf("parseHexMetadata = %v, want %v", got, want)
	}

	if got := parseHexMetadata(`{<<"name">>, <<"x"/utf8>>}.`); got != nil {
		t.Errorf("parseHexMetadata without a licenses field = %v, want nil", got)
	}
}

func TestHexTarballLicences(t *testing.T) {
	var buf bytes.Buffer
	entries := tar.NewWriter(&buf)
	metadata := `{<<"name">>, <<"mist"/utf8>>}.
{<<"licenses">>, [<<"Apache-2.0"/utf8>>]}.
`
	writeTarEntry(t, entries, "metadata.config", metadata)
	writeTarEntry(t, entries, "VERSION", "3")
	if err := entries.Close(); err != nil {
		t.Fatal(err)
	}

	path := filepath.Join(t.TempDir(), "checksum.tar")
	writeFile(t, path, buf.String())

	got, err := hexTarballLicences(path)
	if err != nil {
		t.Fatal(err)
	}
	if want := []string{"Apache-2.0"}; !reflect.DeepEqual(got, want) {
		t.Errorf("hexTarballLicences = %v, want %v", got, want)
	}
}

func writeTarEntry(t *testing.T, entries *tar.Writer, name, body string) {
	t.Helper()
	if err := entries.WriteHeader(&tar.Header{Name: name, Mode: 0o644, Size: int64(len(body))}); err != nil {
		t.Fatal(err)
	}
	if _, err := entries.Write([]byte(body)); err != nil {
		t.Fatal(err)
	}
}

