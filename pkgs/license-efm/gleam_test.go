func writeFile(t *testing.T, path, body string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestParseManifest(t *testing.T) {
	path := filepath.Join(t.TempDir(), manifestFile)
	writeFile(t, path, testManifest)

	pkgs, err := parseManifest(path)
	if err != nil {
		t.Fatal(err)
	}
	want := []manifestPkg{
		{pkgRef: pkgRef{name: "gleam_stdlib", source: "hex", checksum: "960090C2FB391784BB34267B099DC9315CC1B1F6013E7415BC763CEF1905D7D3"}, line: 5, col: 11},
		{pkgRef: pkgRef{name: "gleeunit", source: "hex", checksum: "254B697FE72EEAD7BF82E941723918E421317813AC49923EE76A18C788C61E72"}, line: 6, col: 11},
		{pkgRef: pkgRef{name: "hinoto", source: "git"}, line: 7, col: 11},
	}
	if !reflect.DeepEqual(pkgs, want) {
		t.Errorf("parseManifest:\n got %+v\nwant %+v", pkgs, want)
	}
}

func TestParseGleamToml(t *testing.T) {
	path := filepath.Join(t.TempDir(), gleamFile)
	writeFile(t, path, testGleamToml)

	file, err := parseGleamToml(path)
	if err != nil {
		t.Fatal(err)
	}
	if file.licence != "MIT OR Apache-2.0" {
		t.Errorf("licence = %q, want %q", file.licence, "MIT OR Apache-2.0")
	}
	if file.licenceLine != 3 || file.licenceCol != 1 {
		t.Errorf("licence position = %d:%d, want 3:1", file.licenceLine, file.licenceCol)
	}
	want := []depEntry{
		{name: "gleam_stdlib", line: 9, col: 1},
		{name: "hinoto", line: 10, col: 1},
		{name: "gleeunit", line: 16, col: 1},
	}
	if !reflect.DeepEqual(file.deps, want) {
		t.Errorf("deps:\n got %+v\nwant %+v", file.deps, want)
	}
}

