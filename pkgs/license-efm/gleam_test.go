func TestDiagnosticFormat(t *testing.T) {
	d := diagnostic{file: "/proj/manifest.toml", line: 12, col: 3, severity: severityWarning, message: "unknown licence (not downloaded)"}

	if got, want := d.format(defaultFormat), "/proj/manifest.toml:12:3: W: unknown licence (not downloaded)"; got != want {
		t.Errorf("format = %q, want %q", got, want)
	}
	if got, want := d.format("%f:%l:%c: %m"), "/proj/manifest.toml:12:3: unknown licence (not downloaded)"; got != want {
		t.Errorf("format = %q, want %q", got, want)
	}
	if got, want := d.format("100%% %m"), "100% unknown licence (not downloaded)"; got != want {
		t.Errorf("format = %q, want %q", got, want)
	}
}

// TestScanProject walks a project through the whole pipeline: a directory
// argument, licence lookup in the installed package metadata, and a hex
// dependency that was never downloaded.
func TestScanProject(t *testing.T) {
	root := t.TempDir()
	writeFile(t, filepath.Join(root, gleamFile), testGleamToml)
	writeFile(t, filepath.Join(root, manifestFile), testManifest)
	writeFile(t, filepath.Join(root, buildDir, packagesDir, "gleam_stdlib", gleamFile),
		"name = \"gleam_stdlib\"\nlicences = [\"Apache-2.0\"]\n")
	writeFile(t, filepath.Join(root, buildDir, packagesDir, "hinoto", gleamFile),
		"name = \"hinoto\"\nlicences = [\"MIT\"]\n")

	// Keep the hex cache out of the picture so lookups stay deterministic.
	t.Setenv("GLEAM_CACHE", filepath.Join(root, "empty-cache"))
	t.Setenv("XDG_CACHE_HOME", filepath.Join(root, "empty-cache"))

	got, err := scan(filepath.Join(root, gleamFile), "")
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		"/proj/gleam.toml:3:1: I: MIT OR Apache-2.0",
		"/proj/gleam.toml:9:1: I: Apache-2.0",
		"/proj/gleam.toml:10:1: I: MIT",
		"/proj/gleam.toml:16:1: W: unknown licence (not downloaded)",
	}
	if got := formatAll(got, filepath.Join(root, gleamFile)); !reflect.DeepEqual(got, want) {
		t.Errorf("scan(gleam.toml):\n got %v\nwant %v", got, want)
	}

	got, err = scan(root, "")
	if err != nil {
		t.Fatal(err)
	}
	want = []string{
		"/proj/manifest.toml:5:11: I: Apache-2.0",
		"/proj/manifest.toml:6:11: W: unknown licence (not downloaded)",
		"/proj/manifest.toml:7:11: I: MIT",
	}
	if got := formatAll(got, filepath.Join(root, manifestFile)); !reflect.DeepEqual(got, want) {
		t.Errorf("scan(dir):\n got %v\nwant %v", got, want)
	}
}

// formatAll renders diagnostics against path, which stands in for the temporary
// project directory of a test.
func formatAll(diags []diagnostic, path string) []string {
	const proj = "/proj/"
	out := make([]string, 0, len(diags))
	for _, d := range diags {
		out = append(out, strings.Replace(d.file, filepath.Dir(path)+"/", proj, 1)+d.format(":%l:%c: %t: %m"))
	}
	return out
}
